import assert from 'node:assert/strict';
import {DEFAULTS,calculate,calculateBySession} from './core.mjs';
const s=structuredClone(DEFAULTS);
const r={date:'2026-11-23',shift:'S',dayType:'work',manualBreak:0,intervals:[{start:'08:00',end:'16:00',startOffset:0,endOffset:0},{start:'01:00',end:'03:00',startOffset:1,endOffset:1}],calculationMode:'separate'};
const result=calculateBySession(r,s);
assert.equal(result.net,9);
assert.equal(result.sessions.length,2);
assert.equal(result.sessions[0].net,7);
assert.equal(result.sessions[1].net,2);
assert.equal(result.sessions[0].amount,447133.5);
assert.equal(result.sessions[1].amount,115923.5);
assert.equal(result.amount,563057);
assert.equal(result.automaticBreak,1);
assert.equal(result.bands.filter(b=>b.label.includes('First hour')).length,2);
const legacy=calculateBySession({...r,calculationMode:undefined},s);
assert.equal(legacy.amount,calculate(r,s).amount);
assert.equal(legacy.amount,579617.5);
const overnight=calculateBySession({...r,intervals:[{start:'08:00',end:'16:00'},{start:'01:00',end:'05:00',startOffset:1,endOffset:1}]},s);
assert.equal(overnight.sessions[1].net,4);
assert.equal(overnight.net,11);
const manual=calculateBySession({...r,manualBreak:60},s);
assert.equal(manual.net,8);
assert.equal(manual.sessions[0].net,6);
assert.equal(manual.sessions[1].net,2);
console.log('Separate Before / After session tests passed.');
